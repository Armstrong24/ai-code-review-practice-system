package com.bcorps.database;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Shared H2 database for every module (Member 5: database design).
 *
 * Tables:
 *   students     - Member 1 (registration / login)
 *   problems     - Member 2 (problem bank)
 *   test_cases   - Member 2 (sample + hidden test cases)
 *   submissions  - Member 5 (results of Member 3's engine + Member 4's review)
 *   exam_questions - Learn & Exams (MCQs for each language and the Olympiad)
 *   exam_attempts  - Learn & Exams (each finished exam with its score)
 */
public final class DatabaseManager {
    public static final String DEFAULT_URL = "jdbc:h2:./data/codereview";

    private final String url;

    public DatabaseManager() {
        this(DEFAULT_URL);
    }

    // Used by the self-tests to select a separate in-memory database.
    public DatabaseManager(String url) {
        if (url == null || !url.startsWith("jdbc:h2:")) {
            throw new IllegalArgumentException("An H2 JDBC URL is required.");
        }
        this.url = url;
    }

    public Connection getConnection() throws SQLException {
        // Local development only. Do not use an empty DB password in deployment.
        return DriverManager.getConnection(url, "sa", "");
    }

    public void initialize() throws SQLException {
        try {
            Class.forName("org.h2.Driver");
        } catch (ClassNotFoundException ex) {
            throw new SQLException("H2 driver missing. Add lib/h2-2.5.252.jar to the classpath.", ex);
        }

        String studentsSql = """
            CREATE TABLE IF NOT EXISTS students (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(100) NOT NULL,
                email VARCHAR(200) NOT NULL UNIQUE,
                password_hash VARCHAR(200) NOT NULL,
                password_salt VARCHAR(100) NOT NULL,
                created_at TIMESTAMP NOT NULL
            )
            """;
        String problemsSql = """
            CREATE TABLE IF NOT EXISTS problems (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title VARCHAR(200) NOT NULL,
                description CLOB NOT NULL,
                input_format CLOB NOT NULL,
                output_format CLOB NOT NULL,
                constraints_text CLOB NOT NULL,
                difficulty VARCHAR(10) NOT NULL
                    CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
                category VARCHAR(20) NOT NULL
                    CHECK (category IN ('ARRAYS', 'STRINGS', 'MATH',
                                        'SEARCHING', 'SORTING', 'OTHER'))
            )
            """;
        String testsSql = """
            CREATE TABLE IF NOT EXISTS test_cases (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                problem_id BIGINT NOT NULL,
                input_data CLOB NOT NULL,
                expected_output CLOB NOT NULL,
                is_sample BOOLEAN NOT NULL,
                CONSTRAINT fk_test_problem FOREIGN KEY (problem_id)
                    REFERENCES problems(id) ON DELETE CASCADE
            )
            """;
        String submissionsSql = """
            CREATE TABLE IF NOT EXISTS submissions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id BIGINT NOT NULL,
                problem_id BIGINT NOT NULL,
                source_code CLOB NOT NULL,
                status VARCHAR(30) NOT NULL,
                score DOUBLE NOT NULL,
                passed_tests INT NOT NULL,
                total_tests INT NOT NULL,
                execution_time_ms BIGINT NOT NULL,
                ai_review CLOB,
                submitted_at TIMESTAMP NOT NULL,
                CONSTRAINT fk_sub_student FOREIGN KEY (student_id)
                    REFERENCES students(id) ON DELETE CASCADE,
                CONSTRAINT fk_sub_problem FOREIGN KEY (problem_id)
                    REFERENCES problems(id) ON DELETE CASCADE
            )
            """;

        String examQuestionsSql = """
            CREATE TABLE IF NOT EXISTS exam_questions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                track VARCHAR(20) NOT NULL,
                difficulty VARCHAR(10) NOT NULL
                    CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
                question CLOB NOT NULL,
                code_snippet CLOB,
                option_a VARCHAR(500) NOT NULL,
                option_b VARCHAR(500) NOT NULL,
                option_c VARCHAR(500) NOT NULL,
                option_d VARCHAR(500) NOT NULL,
                correct_option INT NOT NULL CHECK (correct_option BETWEEN 0 AND 3),
                explanation CLOB
            )
            """;
        String examAttemptsSql = """
            CREATE TABLE IF NOT EXISTS exam_attempts (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id BIGINT NOT NULL,
                track VARCHAR(20) NOT NULL,
                correct INT NOT NULL,
                total INT NOT NULL,
                score DOUBLE NOT NULL,
                time_taken_sec INT NOT NULL,
                submitted_at TIMESTAMP NOT NULL,
                CONSTRAINT fk_exam_student FOREIGN KEY (student_id)
                    REFERENCES students(id) ON DELETE CASCADE
            )
            """;

        try (Connection connection = getConnection();
             Statement statement = connection.createStatement()) {
            statement.execute(studentsSql);
            statement.execute(problemsSql);
            statement.execute(testsSql);
            statement.execute(submissionsSql);
            statement.execute(examQuestionsSql);
            statement.execute(examAttemptsSql);
            statement.execute("CREATE INDEX IF NOT EXISTS idx_problem_filter "
                    + "ON problems(difficulty, category)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_test_problem "
                    + "ON test_cases(problem_id, is_sample)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_sub_student "
                    + "ON submissions(student_id, problem_id)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_exam_q_track "
                    + "ON exam_questions(track)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_exam_attempt "
                    + "ON exam_attempts(track, student_id)");
        }
    }
}
